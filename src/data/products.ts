export interface Product {
  slug: string;
  title: string;
  seo: string;
  desc: string;
  pexels: string;
  /** Pre-selected Pexels CDN image URL (no API key required) */
  image: string;
  /** Optional local override — if file exists at /public/products/{slug}.jpg
   *  use that instead of the Pexels URL. AI-generated or owner-supplied
   *  photos go here for a custom catalog. */
  localImage?: string;
  /** Bullet feature list for detail page */
  features: string[];
  /** Use cases / target sectors */
  applications: string[];
  /** Icon SVG path (heroicons-like) */
  icon: string;
}

